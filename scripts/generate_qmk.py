#!/usr/bin/env python3
"""Generate experimental QMK source; no flashing, USB access or implicit build."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "firmware/keyboards/hyperx/alloy_fps_pro"
HID = {0: "KC_NO", **{4 + n: "KC_" + ch for n, ch in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZ")},
       **{30 + n: "KC_" + ch for n, ch in enumerate("1234567890")},
       **{58 + n: f"KC_F{n + 1}" for n in range(12)},
       **dict(zip(range(224, 232), ["KC_LCTL", "KC_LSFT", "KC_LALT", "KC_LGUI", "KC_RCTL", "KC_RSFT", "KC_RALT", "KC_RGUI"])),
       40: "KC_ENT", 41: "KC_ESC", 42: "KC_BSPC", 43: "KC_TAB", 44: "KC_SPC", 45: "KC_MINS",
       46: "KC_EQL", 47: "KC_LBRC", 48: "KC_RBRC", 49: "KC_BSLS", 51: "KC_SCLN", 52: "KC_QUOT",
       53: "KC_GRV", 54: "KC_COMM", 55: "KC_DOT", 56: "KC_SLSH", 57: "KC_CAPS", 70: "KC_PSCR",
       71: "KC_SCRL", 72: "KC_PAUS", 73: "KC_INS", 74: "KC_HOME", 75: "KC_PGUP", 76: "KC_DEL",
       77: "KC_END", 78: "KC_PGDN", 79: "KC_RGHT", 80: "KC_LEFT", 81: "KC_DOWN", 82: "KC_UP",
       101: "KC_APP", 175: "MO(1)"}


def layers(matrix: dict) -> tuple[list[list[str]], list[list[str]], list[list[int]]]:
    default = [[HID[entry["usage"]] for entry in matrix["entries"]]]
    positions = {HID[e["usage"]]: e["matrix"] for e in matrix["entries"] if e["usage"]}
    keys = ["KC_" + ch for ch in "QWERTYUIOPASDFGHJKL"] + ["KC_SCLN"]
    keys += ["KC_" + ch for ch in "ZXCVBNM"] + ["KC_COMM", "KC_DOT", "KC_SLSH"]
    keys += ["KC_TAB", "KC_CAPS", "KC_LSFT", "KC_RSFT", "KC_LCTL", "KC_LGUI", "KC_LALT", "KC_SPC", "KC_RALT", "MO(1)", "KC_APP", "KC_RCTL"]
    active = [positions[key] for key in keys]
    if len(active) != 42 or len({tuple(p) for p in active}) != 42:
        raise ValueError("active physical key set is not 42")
    maps = [["KC_NO"] * 112 for _ in range(4)]
    for key in keys:
        r, c = positions[key]
        maps[0][r * 8 + c] = {"KC_CAPS": "LT(NAV, KC_ESC)", "MO(1)": "MO(SYM)", "KC_RALT": "MO(NUM)"}.get(key, key)
        for layer in maps[1:]:
            layer[r * 8 + c] = "KC_TRNS"
    def assign(layer: int, source: list[str], target: list[str]) -> None:
        if len(source) != len(target):
            raise ValueError("layer mapping length")
        for key, code in zip(source, target):
            r, c = positions[key]
            maps[layer][r * 8 + c] = code
    alpha = lambda text: ["KC_" + ch for ch in text]
    assign(1, alpha("QWERTYUIOP"), ["KC_" + ch for ch in "1234567890"])
    assign(1, alpha("ASDFGHJKL") + ["KC_SCLN"], [f"KC_F{i}" for i in range(1, 11)])
    assign(1, alpha("ZX"), ["KC_F11", "KC_F12"])
    assign(2, alpha("QWERTYUIOP"), [f"S(KC_{ch})" for ch in "1234567890"])
    assign(2, alpha("ASDFGHJKL") + ["KC_SCLN"], ["S(KC_LBRC)", "S(KC_RBRC)", "KC_LBRC", "KC_RBRC", "S(KC_9)", "S(KC_0)", "KC_MINS", "KC_EQL", "KC_BSLS", "KC_GRV"])
    assign(2, alpha("ZXCVBNM") + ["KC_COMM", "KC_DOT", "KC_SLSH"], ["S(KC_COMM)", "S(KC_DOT)", "S(KC_MINS)", "S(KC_EQL)", "S(KC_BSLS)", "S(KC_GRV)", "S(KC_SCLN)", "S(KC_QUOT)", "KC_QUOT", "S(KC_SLSH)"])
    assign(3, alpha("HJKL"), ["KC_LEFT", "KC_DOWN", "KC_UP", "KC_RGHT"])
    assign(3, alpha("QWERTYUIOP"), ["KC_HOME", "KC_UP", "KC_END", "KC_PGUP", "KC_PGDN", "KC_INS", "KC_DEL", "KC_BSPC", "KC_ESC", "KC_ENT"])
    return default, maps, active


def c_source(maps: list[list[str]], custom: bool) -> str:
    text = "// SPDX-License-Identifier: GPL-2.0-or-later\n// Generated by scripts/generate_qmk.py; experimental, not flash-approved.\n#include QMK_KEYBOARD_H\n"
    if custom:
        text += "enum layers { BASE, NUM, SYM, NAV };\n"
    text += "const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {\n"
    for i, layer in enumerate(maps):
        text += f"    [{i}] = {{\n"
        for row in range(14):
            text += "        { " + ", ".join(layer[row * 8:row * 8 + 8]) + " },\n"
        text += "    },\n"
    return text + "};\n"


def with_function_row(matrix: dict, maps: list[list[str]]) -> list[list[str]]:
    """Optional 42+12 variant; keep the original strict 42-key map intact."""
    result = [row.copy() for row in maps]
    for entry in matrix["entries"]:
        if 58 <= entry["usage"] <= 69:
            r, c = entry["matrix"]
            # Direct on ALL layers, even when holding a layer modifier.
            for layer in result:
                layer[r * 8 + c] = HID[entry["usage"]]
    return result


def generate(matrix: dict) -> dict:
    default, maps, active = layers(matrix)
    # Default Fn transparently retains the full TKL map; custom42 supplies useful layers.
    default.append(["KC_TRNS" if key != "KC_NO" else "KC_NO" for key in default[0]])
    layout = [{"matrix": e["matrix"], "x": e["matrix"][1], "y": e["matrix"][0]}
              for e in matrix["entries"] if e["usage"]]
    keyboard = {"keyboard_name": "Alloy FPS Pro custom EXPERIMENTAL", "manufacturer": "alloy-fps-pro-custom",
                "maintainer": "community", "processor": "SN32F268F", "bootloader": "sn32-dfu",
                "usb": {"vid": "0xFEED", "pid": "0xA11F", "device_version": "0.0.1"},
                "diode_direction": "COL2ROW", "matrix_pins": {"rows": matrix["rows"], "cols": matrix["cols"]},
                "debounce": 5, "features": {"bootmagic": True, "extrakey": False, "mousekey": False, "nkro": False},
                "layouts": {"LAYOUT_electrical": {"layout": layout}}}
    DEST.mkdir(parents=True, exist_ok=True)
    (DEST / "keyboard.json").write_text(json.dumps(keyboard, indent=2) + "\n")
    for name, codes, custom in [("default", default, False), ("custom42", maps, True),
                                ("custom42_fn", with_function_row(matrix, maps), True)]:
        folder = DEST / "keymaps" / name
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "keymap.c").write_text(c_source(codes, custom))
    meta = {"active_keys": active, "active_count": 42, "layers": ["BASE", "NUM", "SYM", "NAV"],
            "maps": maps, "matrix_status": matrix["status"], "generator_compiles_firmware": False, "flash_approved": False,
            "build_report": "artifacts/analysis/arm-build-custom42.json",
            "layout_geometry": "electrical_grid_not_physical_TKL", "user_layout_status": "provisional_not_Silakka_export"}
    (DEST / "keymap-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    return meta


if __name__ == "__main__":
    generate(json.loads((ROOT / "hardware/matrix-inference.json").read_text()))
    print("Experimental QMK sources generated: default + custom42 + custom42_fn (42+12), 4 custom layers. No device access.")
