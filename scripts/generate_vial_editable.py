#!/usr/bin/env python3
"""Generate the HyperX ANSI TKL visual layout, not a different board identity.

Physical placement is independent of the inferred 14x8 scan matrix. The five
broken keys retain their physical spaces but are not offered as editable keys.
No USB access and no changes to the persistent map or matrix coordinates.
"""
import argparse
import hashlib
import json
import lzma
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "firmware/keyboards/hyperx/alloy_fps_pro/keymaps/vial_editable"
BROKEN = {37, 38, 39, 45, 46}  # 8 9 0 - =; Backspace is healthy


def physical_rows():
    # (USB HID usage, x in key units, width). Fn is the OEM usage 175.
    fn = [(41, 0, 1)]
    fn += [(58+i, 2+i+(i//4)*0.5, 1) for i in range(12)]
    fn += [(70+i, 15.25+i, 1) for i in range(3)]
    number = [(53, 0, 1)] + [(30+i, 1+i, 1) for i in range(10)]
    number += [(45, 11, 1), (46, 12, 1), (42, 13, 2)]
    number += [(73+i, 15.25+i, 1) for i in range(3)]  # Insert/Home/PgUp
    qrow = [(43, 0, 1.5)] + [(4+ord(c)-ord('A'), 1.5+i, 1) for i, c in enumerate('QWERTYUIOP')]
    qrow += [(47, 11.5, 1), (48, 12.5, 1), (49, 13.5, 1.5)]
    qrow += [(76+i, 15.25+i, 1) for i in range(3)]
    home = [(57, 0, 1.75)] + [(4+ord(c)-ord('A'), 1.75+i, 1) for i, c in enumerate('ASDFGHJKL')]
    home += [(51, 10.75, 1), (52, 11.75, 1), (40, 12.75, 2.25)]
    lower = [(225, 0, 2.25)] + [(4+ord(c)-ord('A'), 2.25+i, 1) for i, c in enumerate('ZXCVBNM')]
    lower += [(54, 9.25, 1), (55, 10.25, 1), (56, 11.25, 1), (229, 12.25, 2.75), (82, 16.25, 1)]
    bottom = [(224, 0, 1.25), (227, 1.25, 1.25), (226, 2.5, 1.25), (44, 3.75, 6.25),
              (230, 10, 1.25), (175, 11.25, 1.25), (101, 12.5, 1.25), (228, 13.75, 1.25),
              (80, 15.25, 1), (81, 16.25, 1), (79, 17.25, 1)]
    return [fn, number, qrow, home, lower, bottom]


def definition(matrix):
    coords = {e['usage']: e['matrix'] for e in matrix['entries'] if e['usage']}
    rows = physical_rows()
    usages = [u for row in rows for u, _, _ in row]
    if len(usages) != 87 or len(set(usages)) != 87 or set(usages) != set(coords):
        raise ValueError('physical layout must cover exactly the inferred 87 keys')
    kle = []
    for index, row in enumerate(rows):
        keys, cursor = [], 0
        if index == 1:
            keys.append({'y': 0.5})  # gap below the function row
        for usage, x, width in row:
            if usage in BROKEN:
                continue
            props = {}
            if x != cursor:
                props['x'] = x-cursor
            if width != 1:
                props['w'] = width
            if props:
                keys.append(props)
            keys.append(','.join(map(str, coords[usage])))
            cursor = x+width
        kle.append(keys)
    return {'name': 'Alloy FPS Pro EDITABLE TEST (ANSI TKL)',
            'vendorId': '0xFEED', 'productId': '0xA11F',
            'matrix': {'rows': 14, 'cols': 8}, 'layouts': {'keymap': kle}}


def generated_files(matrix):
    data = definition(matrix)
    packed = lzma.compress(json.dumps(data, separators=(',', ':')).encode(),
                           format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC64)
    header = ('// SPDX-License-Identifier: GPL-2.0-or-later\n'
              '// Generated by scripts/generate_vial_editable.py; do not edit.\n'
              f'// XZ sha256: {hashlib.sha256(packed).hexdigest()}\n'
              '#pragma once\nstatic const unsigned char alloy_vial_definition[] = {\n')
    for offset in range(0, len(packed), 12):
        header += '    ' + ', '.join(f'0x{b:02x}' for b in packed[offset:offset+12]) + ',\n'
    return {'vial.json': json.dumps(data, indent=2)+'\n', 'definition.h': header+'};\n'}


def generate(check=False):
    matrix = json.loads((ROOT/'hardware/matrix-inference.json').read_text())
    for name, text in generated_files(matrix).items():
        path = DEST/name
        if check:
            if not path.exists() or path.read_text() != text:
                raise ValueError('stale editable definition: '+name)
        else:
            path.write_text(text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
