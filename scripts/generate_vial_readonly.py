#!/usr/bin/env python3
"""Generate a read-only Vial definition from the existing map, without USB."""
import argparse
import hashlib
import json
import lzma
from pathlib import Path

from generate_qmk import layers, with_function_row

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "firmware/keyboards/hyperx/alloy_fps_pro/keymaps/vial_readonly"


def definition(matrix):
    _, maps, _ = layers(matrix)
    base = with_function_row(matrix, maps)[0]
    kle = []
    last_row = -1
    for row in range(14):
        columns = [col for col in range(8) if base[row * 8 + col] != "KC_NO"]
        if not columns:
            continue
        keys = []
        if row != last_row + 1:
            keys.append({"y": row - last_row - 1})
        last_col = -1
        for col in columns:
            if col != last_col + 1:
                keys.append({"x": col - last_col - 1})
            keys.append(f"{row},{col}")
            last_col = col
        kle.append(keys)
        last_row = row
    return {"name": "Alloy FPS Pro READ-ONLY (electrical grid)",
            "vendorId": "0xFEED", "productId": "0xA11F",
            "matrix": {"rows": 14, "cols": 8}, "layouts": {"keymap": kle}}


def generated_files(matrix):
    data = definition(matrix)
    # Same format as pinned Vial generator: compact JSON inside an XZ stream.
    packed = lzma.compress(json.dumps(data, separators=(",", ":")).encode(),
                           format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC64)
    header = ("// SPDX-License-Identifier: GPL-2.0-or-later\n"
              "// Generated by scripts/generate_vial_readonly.py; do not edit.\n"
              "// Cortex-M0: const data resides in flash, not a RAM keymap.\n"
              f"// XZ sha256: {hashlib.sha256(packed).hexdigest()}\n"
              "#pragma once\nstatic const unsigned char alloy_vial_definition[] = {\n")
    for start in range(0, len(packed), 12):
        header += "    " + ", ".join(f"0x{b:02x}" for b in packed[start:start + 12]) + ",\n"
    header += "};\n"
    return {"vial.json": json.dumps(data, indent=2) + "\n", "definition.h": header}


def generate(check=False):
    matrix = json.loads((ROOT / "hardware/matrix-inference.json").read_text())
    for name, text in generated_files(matrix).items():
        target = DEST / name
        if check:
            if not target.is_file() or target.read_text() != text:
                raise ValueError("stale Vial definition: " + name)
        else:
            DEST.mkdir(parents=True, exist_ok=True)
            target.write_text(text)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without changing them")
    generate(parser.parse_args().check)
